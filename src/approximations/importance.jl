export ImportanceSamplingApproximation

using Random
using StatsBase

"""
    ImportanceSamplingApproximation

This structure stores all information needed to perform an importance sampling procedure and provides
convenient functions to generate samples and weights to approximate expectations

# Fields
- `rng`: random number generator objects
- `nsamples`: number of samples generated by default

!!! warning "Not reentrant"
    The sample and weight buffers (`bsamples`, `bweights`, `rsamples`) are preallocated once and
    overwritten in place on every [`approximate_meancov`](@ref) call. A single approximation
    object therefore must not be used by two overlapping evaluations. In particular, if the
    integrand `g` passed to `approximate_meancov` itself calls `approximate_meancov` with the
    *same* approximation object, the inner call overwrites the outer call's buffers and the
    outer result is silently wrong. Construct a separate `ImportanceSamplingApproximation` per
    nesting level if you need that.

    Note that this is a reentrancy constraint, not a thread-safety one: ReactiveMP's schedulers
    (including Rocket's `AsyncScheduler`) are built on `@async` coroutines running on a single
    thread, so two rule evaluations never execute concurrently.

!!! note "Degenerate estimates fall back to the proposal"
    When the weights all vanish, or the resulting moments are non-finite or have zero variance,
    `approximate_meancov` returns the proposal distribution's own `mean`/`var` — a result that
    does not depend on the target at all. This keeps downstream Gaussians non-singular, but it
    is a silent-looking answer, so each such fallback emits a warning (once per session).
"""
struct ImportanceSamplingApproximation{T, R}
    rng        :: R
    nsamples   :: Int
    bsamples   :: Vector{T}
    bweights   :: Vector{T}
    resampling :: Bool
    rsamples   :: Vector{T}
end

function ImportanceSamplingApproximation(
    rng::R, nsamples::Int; resampling::Bool = true
) where {R}
    return ImportanceSamplingApproximation(
        Float64, rng, nsamples; resampling = resampling
    )
end

function ImportanceSamplingApproximation(
    ::Type{T}, rng::R, nsamples::Int; resampling::Bool = true
) where {T, R}
    return ImportanceSamplingApproximation{T, R}(
        rng,
        nsamples,
        Vector{T}(undef, nsamples),
        Vector{T}(undef, nsamples),
        resampling,
        Vector{T}(undef, nsamples),
    )
end

getsamples(approximation::ImportanceSamplingApproximation, distribution)           = getsamples(approximation, distribution, approximation.nsamples)
getsamples(approximation::ImportanceSamplingApproximation, distribution, nsamples) = rand(approximation.rng, distribution, nsamples)

function approximate_meancov(
    approximation::ImportanceSamplingApproximation, g::Function, distribution
)

    # We use preallocated arrays to sample and compute transformed samples and weightd
    rand!(approximation.rng, distribution, approximation.bsamples)
    map!(g, approximation.bweights, approximation.bsamples)

    if approximation.resampling
        # Effective sample size. At this point `bweights` holds the raw `g(z)` values, which
        # are *not* normalized probabilities, so the textbook `1/Σwᵢ²` form does not apply:
        # it is scale-dependent, and would make the `n_eff < N/10` threshold below fire (or
        # not) based on the absolute magnitude of `g` rather than on how uneven the weights
        # are. The scale-invariant definition is used instead:
        #
        #     n_eff = (Σwᵢ)² / Σwᵢ²
        #
        # which reduces to `1/Σwᵢ²` exactly when the weights already sum to one, ranges over
        # [1, N], and equals N for uniform weights regardless of their common value.
        sum_weights  = sum(approximation.bweights)
        sum_weights² = sum(Base.Generator(abs2, approximation.bweights))
        n_eff        = iszero(sum_weights²) ? zero(sum_weights) : abs2(sum_weights) / sum_weights²

        # Here we assume that lengths of bweights ans bsamples vectors are the same
        N = length(approximation.bweights)

        # Resampling is only attempted when the weights are actually resamplable. `sample!`
        # rejects both degenerate cases outright, and reaching it with either would raise an
        # exception that pre-empts the fallbacks further down, turning a handled degenerate
        # estimate into a hard failure:
        #
        #   * all-zero weights  -> `ArgumentError: all weights are zero`
        #   * Inf/NaN weights   -> `ArgumentError: weights cannot contain Inf or NaN values`
        #
        # There is also nothing meaningful to resample in either case. The check is written
        # explicitly rather than relying on `n_eff` being `NaN` (which would make the
        # comparison below false by accident) so the intent survives future edits.
        resamplable =
            !iszero(sum_weights) &&
            isfinite(sum_weights) &&
            isfinite(sum_weights²)

        if resamplable && n_eff < N / 10
            # We use rsamples as a temporary buffer here
            copyto!(approximation.rsamples, 1, approximation.bsamples, 1, N)
            # Here rsamples are equal to bsamples, but during sampling bsamples will be overwritten
            sample!(
                approximation.rng,
                approximation.rsamples,
                Weights(approximation.bweights),
                approximation.bsamples,
            )
            fill!(approximation.bweights, 1 / N)
        end
    end

    normalization = sum(approximation.bweights)

    if iszero(normalization)
        @warn "ImportanceSamplingApproximation: all importance weights are zero; falling back to the proposal's own moments, which ignore the target entirely. Check the integrand and the proposal's support." maxlog =
            1
        return mean(distribution), var(distribution)
    end

    map!(
        Base.Fix2(/, normalization),
        approximation.bweights,
        approximation.bweights,
    )

    m = mapreduce(prod, +, zip(approximation.bweights, approximation.bsamples))

    _v = let m = m
        (r) -> r[1] * (r[2] - m)^2
    end

    v = mapreduce(_v, +, zip(approximation.bweights, approximation.bsamples))

    # `isinf(v)` was missing from this guard, so an infinite variance escaped while an
    # infinite mean did not. Both are now covered.
    #
    # `iszero(v)` is deliberately kept: a zero variance is returned when every surviving
    # sample is identical (typically after resampling collapsed onto one particle), and
    # propagating it would build a singular Gaussian downstream. Falling back to the
    # proposal's variance keeps the result usable, but it is a confident answer that never
    # saw the target, so it now warns instead of substituting silently.
    if isnan(m) || isinf(m) || isnan(v) || isinf(v) || iszero(v)
        @warn "ImportanceSamplingApproximation: degenerate estimate (mean = $(m), variance = $(v)); falling back to the proposal's own moments, which ignore the target entirely. Consider more samples or a better-matched proposal." maxlog =
            1
        return mean(distribution), var(distribution)
    end

    return m, v
end
